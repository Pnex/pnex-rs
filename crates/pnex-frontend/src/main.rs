/// Native inline CSS: the APK does not ship an HTML shell with `<link>` (dx
/// only injects it for the web build) — without inline style, the first DOM
/// patch paints an unstyled frame then restyles (FOUC seen on the emulator).
/// On web the constant is empty: the index.html `<link>` is enough.
#[cfg(not(target_arch = "wasm32"))]
static CSS_INLINE: &str = include_str!("../assets/tailwind.css");
#[cfg(target_arch = "wasm32")]
static CSS_INLINE: &str = "";
// CSS of the media viewers (pannellum controls) — same native inlining
// logic as tailwind.css (the APK has no shell with <link>).
#[cfg(not(target_arch = "wasm32"))]
static VIEWERS_CSS_INLINE: &str = include_str!("../assets/viewers.css");
// maplibre CSS (position:absolute of markers, controls, attribution) —
// generated by js:map (CSS import in js/map.js). WITHOUT it, the HTML markers
// stack under the canvas (normal flow) and become invisible.
static MAP_CSS_INLINE: &str = include_str!("../assets/map.css");
#[cfg(target_arch = "wasm32")]
static VIEWERS_CSS_INLINE: &str = "";

fn main() {
    // Panic hook: the standard stderr message is lost when the JNI abort
    // (panic_cannot_unwind in handleRequest) happens before the flush —
    // message + location are traced explicitly (visible in logcat).
    #[cfg(target_os = "android")]
    std::panic::set_hook(Box::new(|info| {
        eprintln!(
            "PNEX-PANIC: {} @ {}:{}:{}",
            info,
            std::thread::current().name().unwrap_or("?"),
            info.location().map(|l| l.file()).unwrap_or("?"),
            info.location().map(|l| l.line()).unwrap_or(0),
        );
    }));
    // Android logger: without init, the `log::warn!` (capture360, pipeline)
    // go nowhere — and the sensor-sign smoke test needs the poses
    // visible in logcat.
    #[cfg(target_os = "android")]
    {
        let filter = std::env::var("PNEX_LOG").unwrap_or_else(|_| "info".into());
        android_logger::init_once(
            android_logger::Config::default()
                .with_max_level(filter.parse().unwrap_or(log::LevelFilter::Info))
                .with_tag("pnex"),
        );
    }
    dioxus::launch(App);
}

#[component]
fn App() -> Element {
    i18n::init();
    use_hook(state::theme::restore);
    // Session restore (tokens → user-info) once only at boot.
    use_hook(|| {
        spawn(async {
            state::session::boot().await;
        });
    });
    // App ↔ server compatibility gate (API contract): no-op as long as
    // no base is resolved (first native launch). Re-triggered
    // by `apply_server` on every server change.
    use_hook(|| {
        spawn(async {
            state::compat::check().await;
        });
    });
    // Native target with no resolved server URL: the configuration screen
    // replaces the router on first launch (Bitwarden-style). Global:
    // the login page (logout → "Change server") reopens this screen.
    // On web (same-origin) SERVER_READY is always true — see api::config.
    rsx! {
        // Favicon: X mark alone — readable at 32 px, unlike the wordmark.
        link {
            rel: "icon",
            r#type: "image/png",
            href: asset!("/assets/logo-mark.png"),
        }
        // CSS: on web the <link> is already in index.html (dx build, manganis)
        // and blocks rendering. Natively the APK ships no shell with
        // <link> — without inline style, the first DOM patch paints an unstyled
        // frame before the CSS arrives (FOUC seen on the Android emulator,
        // 2026-09-08). include_str! requires the real CSS (task css:build in deps).
        style { {CSS_INLINE} }
        link { rel: "stylesheet", href: asset!("/assets/tailwind.css") }
        // esptool-js glue (browser flash, Web Serial) — classic IIFE script
        // exposing window.pnexFlash/pnexFlashSupported (see flash.rs).
        // Consumed on the "Flash" click, no load-order concern.
        script { src: asset!("/assets/flasher.js") }
        // Animated background of the login page (WebGL2 beam sheaf) —
        // IIFE exposing window.pnexTronGerbe (see tron.rs, login.rs).
        script { src: asset!("/assets/tron-gerbe.js") }
        // WebGL media viewers (pannellum + gsplat.js) — IIFE exposing
        // window.pnexViewers (see media_viewer.rs). pannellum CSS required
        // (controls); inline natively, <link> on web.
        script { src: asset!("/assets/viewers.js") }
        // Geo map (D27) — maplibre-gl 4.x, self-hosted Protomaps style.
        script { src: asset!("/assets/map.js") }
        // Pages editor (pages.md #21) — ProseMirror + Yjs, IIFE exposing
        // window.pnexDoc (see doc_editor.rs).
        script { src: asset!("/assets/doc.js") }
        // Case graph (cases-graph-sigma.md) — Sigma.js + graphology, IIFE
        // exposing window.pnexGraph (see graph_viewer.rs).
        script { src: asset!("/assets/graph.js") }
        style { {VIEWERS_CSS_INLINE} }
        link { rel: "stylesheet", href: asset!("/assets/viewers.css") }
        style { {MAP_CSS_INLINE} }
        link { rel: "stylesheet", href: asset!("/assets/map.css") }
        if !pages::server_url::SERVER_READY() {
            pages::server_url::ServerUrl {}
        } else if state::compat::GATE.cloned() == state::compat::GateState::Ok {
            // Compliant server and same API contract.
            Router::<Route> {}
        } else {
            // Check in progress, server unreachable or different
            // contract: blocking screen (clean refusal).
            pages::gate::GateScreen {}
        }
        // Root CA confirmation (native, D70) — overlay above any screen.
        pages::trust_ca::TrustCaDialog {}
    }
}
