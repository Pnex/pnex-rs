/// Lowest managed role holding `permission`, `None` when unknown.
pub fn permission_level(permission: &str) -> Option<Level> {
    PERMISSIONS
        .iter()
        .find(|(p, _)| *p == permission)
        .map(|(_, l)| *l)
}

/// Who may call `operation_id`, `None` when the registry does not know it.
pub fn operation(operation_id: &str) -> Option<Access> {
    OPERATIONS
        .iter()
        .find(|(id, _)| *id == operation_id)
        .map(|(_, a)| *a)
}

/// Permission an assistant tool needs (`Some(None)` = none, `None` = unknown tool).
pub fn tool(name: &str) -> Option<Option<&'static str>> {
    TOOLS.iter().find(|(t, _)| *t == name).map(|(_, p)| *p)
}
