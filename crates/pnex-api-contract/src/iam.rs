//! IAM action registry (iam.md D289): every operation of the OpenAPI spec
//! declares who may call it, and every org operation the permission
//! (`service:verb`) it needs. The assistant tools are listed the same way.
//! A new route or tool lands here in the same commit; the guard
//! `crates/pnex-backend/tests/iam.rs` fails on an operation or tool missing,
//! listed twice or stale, and on a write reachable through a `read` verb.
//!
//! I1 (managed roles only): the [`Level`] of a permission is the lowest
//! managed role that holds it, a word-for-word translation of D117. Field
//! level gates (a secret value, a share token) and ownership checks (the
//! author of a comment) stay in their handler.

/// Lowest managed role holding a permission (D117 order).
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum Level {
    Viewer,
    Member,
    Admin,
    Owner,
}

/// Who calls an operation. Only [`Access::Org`] goes through the
/// authorization engine; the others keep their own mechanism (iam.md §5.4).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Access {
    /// Org-scoped: the permission the caller needs in the selected org.
    Org(&'static str),
    /// Any signed-in user, outside any org (profile, org list, catalogues).
    User,
    /// Platform administrator (D72).
    Platform,
    /// No credentials (health, meta, sign-in, public links).
    Public,
    /// A machine principal: device, edge agent, browser agent.
    Machine,
}

